#!/usr/bin/env python3
"""Generate host_auth v2 test vectors with independent implementations.

Signatures come from pyca/cryptography (OpenSSL): the same P-256/SHA-256 ECDSA
that the Secure Enclave, Windows Hello and FIDO2 keys produce, DER-encoded as
WebAuthn carries them. The client data JSON is built here independently and,
when python-fido2 is installed, checked byte for byte against
fido2.webauthn.CollectedClientData.create, which is what the Windows/Linux
tool sends.
"""
import base64
import hashlib
import json
import os
import struct
import sys

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import (
    decode_dss_signature,
    encode_dss_signature,
)

TAG = b"flipware-hostauth-v2"
RP_ID = "hostauth.flipware.local"
ORIGIN = "https://hostauth.flipware.local"
N = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551

UP, UV, BE, BS, AT, ED = 0x01, 0x04, 0x08, 0x10, 0x40, 0x80

# Must match HostAuthVerifyResult
RESULTS = {
    "ok": "HostAuthVerifyOk",
    "bad_sig": "HostAuthVerifyBadSignature",
    "rp": "HostAuthVerifyRpMismatch",
    "no_up": "HostAuthVerifyNoPresence",
    "no_uv": "HostAuthVerifyNoVerification",
    "synced": "HostAuthVerifySynced",
    "flags": "HostAuthVerifyBadFlags",
    "counter": "HostAuthVerifyCounter",
}


def b64url(data):
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def binding(action, uid, epoch, counter, nonce):
    return TAG + bytes([action, len(uid)]) + uid + struct.pack(">II", epoch, counter) + nonce


def client_data(challenge_b64):
    data = json.dumps(
        {
            "type": "webauthn.get",
            "challenge": challenge_b64,
            "origin": ORIGIN,
            "crossOrigin": False,
        },
        separators=(",", ":"),
    ).encode()
    try:
        from fido2.webauthn import CollectedClientData
    except ImportError:
        return data, False
    ref = bytes(CollectedClientData.create(type="webauthn.get", challenge=challenge_b64, origin=ORIGIN))
    assert ref == data, (ref, data)
    return data, True


def c_bytes(data):
    return "{" + ", ".join(f"0x{b:02x}" for b in data) + "}"


def c_string(data):
    return '"' + data.decode().replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(out_path):
    cases = [
        # name, flags, sign_count, stored_count, require_uv, expected, rp_ok, high_s
        ("up_uv", UP | UV, 0, 0, True, "ok", True, False),
        ("up_only", UP, 0, 0, False, "ok", True, False),
        ("counter_up", UP | UV, 7, 6, True, "ok", True, False),
        ("counter_same", UP | UV, 7, 7, True, "counter", True, False),
        ("counter_back", UP | UV, 3, 7, True, "counter", True, False),
        ("counter_zero_after", UP | UV, 0, 7, True, "counter", True, False),
        ("uv_required", UP, 0, 0, True, "no_uv", True, False),
        ("no_up", UV, 0, 0, False, "no_up", True, False),
        ("synced_be", UP | UV | BE, 0, 0, True, "synced", True, False),
        ("synced_bs", UP | UV | BE | BS, 0, 0, True, "synced", True, False),
        ("attested", UP | UV | AT, 0, 0, True, "flags", True, False),
        ("extensions", UP | UV | ED, 0, 0, True, "flags", True, False),
        ("reserved_bit", UP | 0x02, 0, 0, False, "flags", True, False),
        ("other_rp", UP | UV, 0, 0, True, "rp", False, False),
        ("high_s", UP | UV, 0, 0, True, "ok", True, True),
    ]

    fido2_checked = False
    lines = [
        "// Generated by gen_vectors.py. Do not edit.\n",
        "#pragma once\n",
        "#include <stddef.h>\n",
        "#include <stdint.h>\n",
        "#include <stdbool.h>\n",
        "typedef struct {\n",
        "    const char* name;\n",
        "    uint8_t pub[65];\n",
        "    uint8_t uid[8];\n",
        "    uint32_t epoch, counter;\n",
        "    uint8_t nonce[32];\n",
        "    const char* challenge;\n",
        "    const char* client_data;\n",
        "    uint8_t auth_data[37];\n",
        "    uint8_t der[72];\n",
        "    size_t der_len;\n",
        "    uint8_t fp[8];\n",
        "    bool require_uv;\n",
        "    uint32_t stored_count, sign_count;\n",
        "    int expected;\n",
        "} Vec;\n",
        "static const Vec vectors[] = {\n",
    ]
    for name, flags, count, stored, require_uv, expected, rp_ok, high_s in cases:
        key = ec.generate_private_key(ec.SECP256R1())
        pub = key.public_key().public_bytes(
            serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint
        )
        uid = os.urandom(8)
        epoch = int.from_bytes(os.urandom(4), "big") | 1
        counter = int.from_bytes(os.urandom(3), "big") + 1
        nonce = os.urandom(32)
        b = binding(1, uid, epoch, counter, nonce)
        challenge = b64url(b)
        cd, checked = client_data(challenge)
        fido2_checked = fido2_checked or checked
        rp = RP_ID if rp_ok else "evil.example"
        auth_data = hashlib.sha256(rp.encode()).digest() + bytes([flags]) + struct.pack(">I", count)
        assert len(auth_data) == 37
        der = key.sign(auth_data + hashlib.sha256(cd).digest(), ec.ECDSA(hashes.SHA256()))
        if high_s:
            r, s = decode_dss_signature(der)
            if s <= N // 2:
                s = N - s
            der = encode_dss_signature(r, s)
        fp = hashlib.sha256(pub).digest()[:8]
        lines.append(
            "    {"
            f'"{name}", {c_bytes(pub)}, {c_bytes(uid)}, {epoch}u, {counter}u, {c_bytes(nonce)}, '
            f'"{challenge}", {c_string(cd)}, {c_bytes(auth_data)}, {c_bytes(der)}, {len(der)}, '
            f"{c_bytes(fp)}, {'true' if require_uv else 'false'}, {stored}u, {count}u, "
            f"{RESULTS[expected]}"
            "},\n"
        )
    lines.append("};\n")
    lines.append("#define VEC_COUNT (sizeof(vectors) / sizeof(vectors[0]))\n")
    lines.append(f"#define VEC_FIDO2_CHECKED {1 if fido2_checked else 0}\n")
    with open(out_path, "w") as f:
        f.writelines(lines)
    print("client data checked against python-fido2:", "yes" if fido2_checked else "no (not installed)")


if __name__ == "__main__":
    main(sys.argv[1])
