#!/usr/bin/env python3
"""Generate host_auth test vectors with an independent ECDSA implementation.

Uses pyca/cryptography (OpenSSL), the same P-256/SHA-256 ECDSA that Apple's
CryptoKit and Secure Enclave produce. Signatures are emitted as raw r || s,
matching CryptoKit's `rawRepresentation`.
"""
import hashlib
import os
import sys

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature

TAG = b"flipware-hostauth-v1"


def message(action, uid, nonce):
    return TAG + bytes([action, len(uid)]) + uid + nonce


def c_array(name, data):
    body = ", ".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[{len(data)}] = {{{body}}};\n"


def main(out_path):
    count = 8
    lines = ["// Generated by gen_vectors.py. Do not edit.\n", "#pragma once\n", "#include <stdint.h>\n"]
    lines.append(f"#define VEC_COUNT {count}\n")
    entries = []
    for i in range(count):
        key = ec.generate_private_key(ec.SECP256R1())
        pub = key.public_key().public_bytes(
            serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint
        )
        uid = os.urandom(8)
        nonce = os.urandom(32)
        msg = message(1, uid, nonce)
        der = key.sign(msg, ec.ECDSA(hashes.SHA256()))
        r, s = decode_dss_signature(der)
        sig = r.to_bytes(32, "big") + s.to_bytes(32, "big")
        fp = hashlib.sha256(pub).digest()[:8]
        lines.append(c_array(f"vec{i}_pub", pub))
        lines.append(c_array(f"vec{i}_uid", uid))
        lines.append(c_array(f"vec{i}_nonce", nonce))
        lines.append(c_array(f"vec{i}_sig", sig))
        lines.append(c_array(f"vec{i}_fp", fp))
        entries.append(i)
    lines.append("typedef struct { const uint8_t *pub, *uid, *nonce, *sig, *fp; } Vec;\n")
    lines.append("static const Vec vectors[VEC_COUNT] = {\n")
    for i in entries:
        lines.append(f"    {{vec{i}_pub, vec{i}_uid, vec{i}_nonce, vec{i}_sig, vec{i}_fp}},\n")
    lines.append("};\n")
    with open(out_path, "w") as f:
        f.writelines(lines)


if __name__ == "__main__":
    main(sys.argv[1])
